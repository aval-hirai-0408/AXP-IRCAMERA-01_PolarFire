//**********************************************************************************
//	wfi - wait fir interrupt
//----------------------------------------------------------------------------------
//	[ INPUT ]
//		-
//	[ OUTPUT ]
//		-
//==================================================================================
inline void cpu_wfi (void)
{
	 __asm volatile ("wfi" ::: "memory");
}


//**********************************************************************************
//	Enable MIE - mstatus.MIE = 1 : ISRへの突入を許可させる。
//----------------------------------------------------------------------------------
//	[ INPUT ]
//		-
//	[ OUTPUT ]
//		-
//==================================================================================
inline void enable_global_irq (void)
{
	__asm volatile ("csrs mstatus, %0"
					:
					: "r"(0x8)
					: "memory");
}


//**********************************************************************************
//	Disable MIE - mstatus.MIE = 0 : ISRへの突入を禁止させる。Pending状態になる。
//----------------------------------------------------------------------------------
//	[ INPUT ]
//		-
//	[ OUTPUT ]
//		-
//==================================================================================
inline void disable_global_irq (void)
{
	__asm volatile ("csrc mstatus, %0"
					:
					: "r"(0x8)
					: "memory");
}


//**********************************************************************************
//	Enable MIE - mstatus.MIE = 1 : ISRへの突入を許可させる。
//----------------------------------------------------------------------------------
//	[ INPUT ]
//		-
//	[ OUTPUT ]
//		-
//==================================================================================
inline void irq_restore_Mie (uintptr_t old_mstatus)
{
	if (old_mstatus & MSTATUS_MIE)
	{
		__asm volatile ("csrs mstatus, %0"
						:
						: "r"(MSTATUS_MIE)
						: "memory");
	}
}


//**********************************************************************************
//	Disable MIE - mstatus.MIE = 0 : ISRへの突入を禁止させる。Pending状態になる。
//----------------------------------------------------------------------------------
//	[ INPUT ]
//		-
//	[ OUTPUT ]
//		-
//==================================================================================
inline uintptr_t irq_save_disable_Mie (void)
{
	uintptr_t old_mstatus;

	__asm volatile ("csrrc %0, mstatus, %1"
					: "=r"(old_mstatus)
					: "r"(MSTATUS_MIE)
					: "memory");

	return (old_mstatus);
}

